namespace Sprite {
  static constexpr const uint8_t SIZE = 4;
  static constexpr const uint8_t BITS = SIZE * SIZE;

  enum Part : uint8_t {
    TAIL_TO_UP = 0,
    TAIL_TO_RIGHT,
    TAIL_TO_DOWN,
    TAIL_TO_LEFT,

    BODY_TO_UP,
    BODY_TO_RIGHT,
    BODY_TO_DOWN,
    BODY_TO_LEFT,

    CORNER_RIGHT_UP,
    CORNER_RIGHT_DOWN,
    CORNER_LEFT_UP,
    CORNER_LEFT_DOWN,

    HEAD_UP_CLOSE,
    HEAD_RIGHT_CLOSE,
    HEAD_DOWN_CLOSE,
    HEAD_LEFT_CLOSE,

    HEAD_UP_OPEN,
    HEAD_RIGHT_OPEN,
    HEAD_DOWN_OPEN,
    HEAD_LEFT_OPEN,

    BELLY_TO_RIGHT,
    BELLY_TO_LEFT,
    BELLY_RIGHT_UP,
    BELLY_RIGHT_DOWN,
    BELLY_LEFT_UP,
    BELLY_LEFT_DOWN,

    EMPTY,

    COUNT
  };

  static constexpr const uint16_t SPRITES[COUNT] = {
    0b0110'0110'0100'0100, 0b0000'0011'1111'0000, 0b0100'0100'0110'0110, 0b0000'1100'1111'0000, // Tail
    0b0110'0100'0010'0110, 0b0000'1101'1011'0000, 0b0110'0010'0100'0110, 0b0000'1011'1101'0000, // Body
    0b0110'0101'0011'0000, 0b0000'0011'0101'0110, 0b0110'1010'1100'0000, 0b0000'1100'1010'0110, // Corner
    0b0000'0110'0110'0101, 0b1000'0110'1110'0000, 0b0101'0110'0110'0000, 0b0001'0110'0111'0000, // Head close
    0b0000'1001'0110'0101, 0b1010'0100'1100'0010, 0b0101'0110'1001'0000, 0b0101'0010'0011'0100, // Head open
    0b0110'1101'1011'0110, 0b0110'1011'1101'0110, 0b0111'0101'0011'0000, 0b0000'0011'0101'0111, 0b1110'1010'1100'0000, 0b0000'1100'1010'1110, // Belly
    0b0000'0000'0000'0000 // Empty
  };

  static constexpr const bool pixel(Part part, uint8_t x, uint8_t y) {
    return (SPRITES[(uint8_t)part] & ((uint16_t)1 << (BITS - 1 - (y * SIZE + x)))) != 0;
  }
}

namespace Special {
  static constexpr const uint8_t SPECIAL_FOOD_W = 8;
  static constexpr const uint8_t SPECIAL_FOOD_H = 4;

  static constexpr const uint8_t COUNT = 2;

  static constexpr const uint32_t SPECIAL_FOOD[COUNT] = {
    0b0101'0100'1011'1110'1111'1111'0010'0100, // Sprite 0
    0b0000'0000'0000'0000'0000'0000'0000'0000  // Empty
  };

  static constexpr const bool specialPixel(uint8_t sprite, uint8_t x, uint8_t y) {
    if (sprite >= COUNT) sprite = COUNT;
    return (SPECIAL_FOOD[sprite] & (0x8000'0000UL >> (y * SPECIAL_FOOD_W + x))) != 0;
  }
}

